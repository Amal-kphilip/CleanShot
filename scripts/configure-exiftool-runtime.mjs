import { readFile, writeFile, appendFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packagePath = path.join(root, 'package.json');
const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
packageJson.dependencies ??= {};
packageJson.scripts ??= {};
// Pin the maintained WebAssembly wrapper that bundles ExifTool 13.59.
// Remove the older wrapper if a previous partial install added it.
delete packageJson.dependencies['@uswriting/exiftool'];
packageJson.dependencies['@lilohuang/exiftool'] = '1.0.10';

const copyCommand = 'node scripts/copy-exiftool-wasm.mjs';
const existingPostinstall = packageJson.scripts.postinstall;
if (!existingPostinstall) {
  packageJson.scripts.postinstall = copyCommand;
} else if (!existingPostinstall.includes(copyCommand)) {
  packageJson.scripts.postinstall = `${existingPostinstall} && ${copyCommand}`;
}

await writeFile(packagePath, `${JSON.stringify(packageJson, null, 2)}\n`, 'utf8');

const ignorePath = path.join(root, '.gitignore');
let ignoreText = '';
try {
  ignoreText = await readFile(ignorePath, 'utf8');
} catch {
  // A new .gitignore will be created if needed.
}
if (!ignoreText.split(/\r?\n/).some((line) => line.trim() === '/public/zeroperl.wasm')) {
  await appendFile(ignorePath, `${ignoreText.endsWith('\n') || ignoreText.length === 0 ? '' : '\n'}# Generated by the install script for local-browser ExifTool scans\n/public/zeroperl.wasm\n`, 'utf8');
}

console.log('Configured @lilohuang/exiftool 1.0.10 (ExifTool 13.59) and a postinstall step without changing other dependency or build-script versions.');
