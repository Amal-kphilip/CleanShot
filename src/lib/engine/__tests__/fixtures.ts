// Minimal 1x1 red pixel JPEG with APP1 (EXIF), APP2 (ICC), and COM segments
export function createSampleJpegWithMetadata(): Uint8Array {
  // SOI
  const soi = [0xFF, 0xD8];

  // APP0 (JFIF)
  const app0 = [
    0xFF, 0xE0, 0x00, 0x10, 0x4A, 0x46, 0x49, 0x46, 0x00, 0x01, 0x01, 0x00, 0x00,
    0x01, 0x00, 0x01, 0x00, 0x00,
  ];

  // APP1 (EXIF with GPS & Camera metadata)
  const exifPayload = [
    0x45, 0x78, 0x69, 0x66, 0x00, 0x00, // "Exif\0\0"
    0x49, 0x49, 0x2A, 0x00, 0x08, 0x00, 0x00, 0x00, // TIFF Header (Little Endian)
    0x02, 0x00, // 2 IFD entries
    0x0F, 0x01, 0x02, 0x00, 0x05, 0x00, 0x00, 0x00, 0x26, 0x00, 0x00, 0x00, // Make (tag 0x010F) -> "Sony"
    0x10, 0x01, 0x02, 0x00, 0x06, 0x00, 0x00, 0x00, 0x2C, 0x00, 0x00, 0x00, // Model (tag 0x0110) -> "A7IV"
    0x00, 0x00, 0x00, 0x00, // Next IFD
    0x53, 0x6F, 0x6E, 0x79, 0x00, // "Sony\0"
    0x41, 0x37, 0x49, 0x56, 0x00, 0x00, // "A7IV\0\0"
  ];
  const app1Len = exifPayload.length + 2;
  const app1 = [0xFF, 0xE1, (app1Len >> 8) & 0xFF, app1Len & 0xFF, ...exifPayload];

  // COM (Comment)
  const comText = [0x54, 0x61, 0x6B, 0x65, 0x6E, 0x20, 0x62, 0x79, 0x20, 0x4A, 0x6F, 0x68, 0x6E]; // "Taken by John"
  const comLen = comText.length + 2;
  const com = [0xFF, 0xFE, (comLen >> 8) & 0xFF, comLen & 0xFF, ...comText];

  // DQT (Quantization Table)
  const dqt = [
    0xFF, 0xDB, 0x00, 0x43, 0x00,
    ...new Array(64).fill(16),
  ];

  // SOF0 (Baseline DCT 1x1 pixel)
  const sof0 = [
    0xFF, 0xC0, 0x00, 0x0B, 0x08, 0x00, 0x01, 0x00, 0x01, 0x01, 0x01, 0x11, 0x00
  ];

  // DHT (Huffman Table)
  const dht = [
    0xFF, 0xC4, 0x00, 0x1F, 0x00,
    0x00, 0x01, 0x05, 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
    0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B
  ];

  // SOS (Start of Scan) + 1 byte entropy data + EOI
  const sos = [0xFF, 0xDA, 0x00, 0x08, 0x01, 0x01, 0x00, 0x00, 0x3F, 0x00];
  const scanData = [0x7F];
  const eoi = [0xFF, 0xD9];

  return new Uint8Array([
    ...soi,
    ...app0,
    ...app1,
    ...com,
    ...dqt,
    ...sof0,
    ...dht,
    ...sos,
    ...scanData,
    ...eoi,
  ]);
}

// Minimal 1x1 PNG with tEXt metadata chunk
export function createSamplePngWithMetadata(): Uint8Array {
  // Signature
  const sig = [0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A];

  // IHDR (1x1, 8-bit RGBA)
  const ihdrData = [
    0x00, 0x00, 0x00, 0x01, // width: 1
    0x00, 0x00, 0x00, 0x01, // height: 1
    0x08, 0x06, 0x00, 0x00, 0x00,
  ];
  const ihdrChunk = [
    0x00, 0x00, 0x00, 0x0D, // len: 13
    0x49, 0x48, 0x44, 0x52, // "IHDR"
    ...ihdrData,
    0x5D, 0x2A, 0x22, 0x4B, // CRC
  ];

  // tEXt chunk ("Author\0Jane Doe")
  const textPayload = [
    0x41, 0x75, 0x74, 0x68, 0x6F, 0x72, 0x00, // "Author\0"
    0x4A, 0x61, 0x6E, 0x65, 0x20, 0x44, 0x6F, 0x65, // "Jane Doe"
  ];
  const textLen = textPayload.length;
  const textChunk = [
    (textLen >> 24) & 0xFF, (textLen >> 16) & 0xFF, (textLen >> 8) & 0xFF, textLen & 0xFF,
    0x74, 0x45, 0x58, 0x74, // "tEXt"
    ...textPayload,
    0x00, 0x00, 0x00, 0x00, // dummy CRC
  ];

  // IDAT (1x1 uncompressed deflate stream)
  const idatData = [0x78, 0x9C, 0x63, 0xF8, 0xCF, 0xC0, 0x00, 0x00, 0x03, 0x01, 0x01, 0x00];
  const idatLen = idatData.length;
  const idatChunk = [
    (idatLen >> 24) & 0xFF, (idatLen >> 16) & 0xFF, (idatLen >> 8) & 0xFF, idatLen & 0xFF,
    0x49, 0x44, 0x41, 0x54, // "IDAT"
    ...idatData,
    0x18, 0xDD, 0x8D, 0xB0,
  ];

  // IEND
  const iendChunk = [
    0x00, 0x00, 0x00, 0x00,
    0x49, 0x45, 0x4E, 0x44,
    0xAE, 0x42, 0x60, 0x82,
  ];

  return new Uint8Array([
    ...sig,
    ...ihdrChunk,
    ...textChunk,
    ...idatChunk,
    ...iendChunk,
  ]);
}

// Minimal WebP with EXIF chunk
export function createSampleWebpWithMetadata(): Uint8Array {
  // VP8X header (flags = 0x08 for EXIF)
  const vp8xPayload = [
    0x08, 0x00, 0x00, 0x00, // flags (EXIF bit set)
    0x00, 0x00, 0x00,       // canvas width - 1 (1px)
    0x00, 0x00, 0x00,       // canvas height - 1 (1px)
  ];
  const vp8xChunk = [
    0x56, 0x50, 0x38, 0x58, // "VP8X"
    0x0A, 0x00, 0x00, 0x00, // length: 10
    ...vp8xPayload,
  ];

  // EXIF chunk
  const exifPayload = [0x45, 0x78, 0x69, 0x66, 0x00, 0x00, 0x01, 0x02];
  const exifChunk = [
    0x45, 0x58, 0x49, 0x46, // "EXIF"
    0x08, 0x00, 0x00, 0x00, // length: 8
    ...exifPayload,
  ];

  // VP8 chunk (minimal frame)
  const vp8Payload = [0x30, 0x01, 0x00, 0x9D, 0x01, 0x2A, 0x01, 0x00, 0x01, 0x00];
  const vp8Chunk = [
    0x56, 0x50, 0x38, 0x20, // "VP8 "
    0x0A, 0x00, 0x00, 0x00, // length: 10
    ...vp8Payload,
  ];

  const totalChunks = [...vp8xChunk, ...exifChunk, ...vp8Chunk];
  const riffSize = 4 + totalChunks.length;

  return new Uint8Array([
    0x52, 0x49, 0x46, 0x46, // "RIFF"
    riffSize & 0xFF, (riffSize >> 8) & 0xFF, (riffSize >> 16) & 0xFF, (riffSize >> 24) & 0xFF,
    0x57, 0x45, 0x42, 0x50, // "WEBP"
    ...totalChunks,
  ]);
}

